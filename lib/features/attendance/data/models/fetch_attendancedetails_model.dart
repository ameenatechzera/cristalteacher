import 'package:cristalteacher/features/attendance/domain/entities/fetch_attendancedetails_entity.dart';

class AttendanceDetailsResponseModel extends AttendanceDetailsEntity {
  AttendanceDetailsResponseModel({
    super.status,
    super.error,
    super.message,
    List<AttendanceDetailsModel>? super.data,
  });

  factory AttendanceDetailsResponseModel.fromJson(Map<String, dynamic> json) {
    return AttendanceDetailsResponseModel(
      status: json['status'] as int?,
      error: json['error'] as bool?,
      message: json['message']?.toString(),
      data: (json['data'] as List?)
          ?.map(
            (e) => AttendanceDetailsModel.fromJson(e as Map<String, dynamic>),
          )
          .toList(),
    );
  }
}

